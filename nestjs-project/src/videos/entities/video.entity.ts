import {
  Column,
  CreateDateColumn,
  Entity,
  Index,
  JoinColumn,
  ManyToOne,
  PrimaryColumn,
  UpdateDateColumn,
  type ValueTransformer,
} from 'typeorm';
import { Channel } from '../../channels/entities/channel.entity';

export enum VideoStatus {
  DRAFT = 'draft',
  PROCESSING = 'processing',
  READY = 'ready',
  FAILED = 'failed',
}

export enum VideoProcessingError {
  UNSUPPORTED_MEDIA = 'UNSUPPORTED_MEDIA',
  PROCESSING_FAILED = 'PROCESSING_FAILED',
  UPLOAD_EXPIRED = 'UPLOAD_EXPIRED',
}

export interface VideoMetadata {
  width: number;
  height: number;
  video_codec: string;
  audio_codec: string | null;
  bit_rate: number | null;
  frame_rate: number | null;
  format_name: string;
}

// node-postgres reads bigint as string; 10 GiB stays within Number.MAX_SAFE_INTEGER.
const bigintToNumber: ValueTransformer = {
  to: (value: number) => value,
  from: (value: string | null) => (value === null ? null : Number(value)),
};

@Entity('videos')
export class Video {
  // Generated by the service before CreateMultipartUpload: the storage key depends on it.
  @PrimaryColumn('uuid')
  id: string;

  @Column({ type: 'varchar', length: 11, unique: true })
  public_id: string;

  @Index()
  @Column({ type: 'uuid' })
  channel_id: string;

  @Column({ type: 'varchar', length: 100 })
  title: string;

  @Column({ type: 'varchar', length: 255 })
  original_filename: string;

  @Column({ type: 'varchar', length: 50 })
  mime_type: string;

  @Column({ type: 'bigint', transformer: bigintToNumber })
  size_bytes: number;

  @Column({ type: 'enum', enum: VideoStatus, default: VideoStatus.DRAFT })
  status: VideoStatus;

  @Column({ type: 'enum', enum: VideoProcessingError, nullable: true })
  processing_error: VideoProcessingError | null;

  @Column({ type: 'varchar', length: 1024 })
  upload_id: string;

  @Column({ type: 'timestamp' })
  upload_expires_at: Date;

  @Column({ type: 'double precision', nullable: true })
  duration_seconds: number | null;

  @Column({ type: 'jsonb', nullable: true })
  metadata: VideoMetadata | null;

  @Column({ type: 'varchar', length: 255, nullable: true })
  thumbnail_key: string | null;

  @CreateDateColumn()
  created_at: Date;

  @UpdateDateColumn()
  updated_at: Date;

  @ManyToOne(() => Channel, (channel) => channel.videos)
  @JoinColumn({ name: 'channel_id' })
  channel: Channel;
}
